      PROGRAM DUMP2
      INTEGER MAXDIM, NBITS
      PARAMETER (MAXDIM=318,NBITS=31)
      INTEGER SCJ(MAXDIM,0:NBITS-1), DIMEN, COUNT, NEXTQ(MAXDIM)
      COMMON /COMM2/SCJ,DIMEN,COUNT,NEXTQ
      DOUBLE PRECISION OUTS(MAXDIM,10000)
      INTEGER I,J
      EXTERNAL GNNIED
      CALL GNNIED(2,4096,1,OUTS)
      DO 10 I = 1,2
          WRITE (*,FMT=*) "SCJ", I, (SCJ(I,J), J=0,5)
   10 CONTINUE
      STOP
      END
