      PROGRAM DUMP4
      INTEGER MAXDIM, NBITS
      PARAMETER (MAXDIM=318,NBITS=31)
      INTEGER LSM(MAXDIM,0:NBITS), SHIFT(MAXDIM)
      INTEGER I,J
      EXTERNAL GNCRML
      CALL GNCRML(MAXDIM,NBITS,2,LSM,SHIFT)
      WRITE (*,FMT=*) "SHIFT", SHIFT(1), SHIFT(2)
      DO 10 I = 1,2
          WRITE (*,FMT=*) "LSM", I, (LSM(I,J), J=0,4)
   10 CONTINUE
      STOP
      END
