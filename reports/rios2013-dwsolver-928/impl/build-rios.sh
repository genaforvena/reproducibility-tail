#!/bin/sh
# Runs inside the sandbox (cwd /work). Usage: sh /work/build-rios.sh orig|pat
# orig: the authors' tree as shipped (C/ with Src/src), configure and make, no change.
# pat:  build layout and flags only, no source edit:
#       1. ln -s Src/src src (configure.ac and the top-level Makefile.in expect C/src/, the archive ships C/Src/src/)
#       2. CPPFLAGS=-I/work/pat so src/*.c finds the top-level config.h (configure writes it in C/, not in src/)
#       3. CFLAGS=-fcommon: dw.h defines globals without extern; GCC 10+ defaults to -fno-common and the link fails
#       4. the libtool wrapper ../libtool is not generated by configure here, so the final link is the same gcc
#          command with the same objects and libraries (-lm -lpthread)
set -u
case "${1:-}" in
orig)
  rm -rf orig && cp -r src/928/C orig && cd orig
  ./configure > /work/configure-orig.log 2>&1; echo "CONFIGURE $?"
  make -j2 > /work/make-orig.log 2>&1; echo "MAKE $?"
  ;;
pat)
  rm -rf pat && cp -r src/928/C pat && cd pat
  ln -s Src/src src
  ./configure > /work/configure-pat.log 2>&1; echo "CONFIGURE $?"
  cd Src/src
  make -k -j2 CFLAGS="-g -O2 -fcommon" CPPFLAGS=-I/work/pat > /work/make-pat.log 2>&1; echo "MAKE-OBJECTS $?"
  echo "OBJECTS $(ls dwsolver-*.o | wc -l)"
  gcc -g -O2 -fcommon -o dwsolver dwsolver-*.o -lm -lpthread && cp dwsolver /work/dwsolver && echo "LINK 0"
  ;;
*) echo "usage: build-rios.sh orig|pat" >&2; exit 2 ;;
esac
